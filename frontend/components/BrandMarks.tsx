/** A mark as its own inline SVG, `height` pixels tall. Decorative. */
export function Mark({
  id,
  height,
  className,
  style,
}: {
  id: MarkId
  height: number
  className?: string
  style?: React.CSSProperties
}) {
  const w = 24 * RATIO[id]
  return (
    <svg
      viewBox={`0 0 ${w} 24`}
      width={markWidth(id, height)}
      height={height}
      className={className}
      style={style}
      aria-hidden="true"
      focusable="false"
    >
      <use href={`#wm-${id}`} width={w} height={24} />
    </svg>
  )
}

/** A mark placed inside another SVG, at (x, y) and `height` units tall. */
export function SvgMark({ id, x, y, height, className }: { id: MarkId; x: number; y: number; height: number; className?: string }) {
  return <use href={`#wm-${id}`} x={x} y={y} width={markWidth(id, height)} height={height} className={className} />
}
